let lang = 'en';

/** Accepts 'pt-BR', 'DE', etc. Unknown languages fall back to English. */
export function setLang(code) {
  const base = String(code || '').toLowerCase().split(/[-_]/)[0];
  lang = STR[base] ? base : 'en';
  document.documentElement.lang = lang;
  return lang;
}

export const getLang = () => lang;

export function t(key, vars) {
  const s = STR[lang][key] ?? STR.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k]) : s;
}

/** Fill every element marked with data-i18n. The strings are ours, so markup in them is safe. */
export function applyDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.innerHTML = t(el.dataset.i18n);
}
